import { afterEach, describe, expect, it, vi } from "vitest";
import { render, screen, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { api } from "../api";
import { AnalyzeTab } from "../components/AnalyzeTab";
import { ResultCard, type AnalysisRun } from "../components/ResultCard";
import { ToastProvider } from "../components/Toast";
import { TopBar } from "../components/TopBar";
import type { AnalysisResponse, HealthResponse, ModelStatus } from "../types";

const health = (codeSummarizer: ModelStatus): HealthResponse => ({
  status: "ok",
  models: {
    tfidf: { status: "loaded" },
    codebert: { status: "unavailable" },
    summarizer: { status: "unavailable" },
    code_summarizer: { status: codeSummarizer },
  },
});

const base: AnalysisResponse = {
  label: "CLEAN",
  bug_probability: 0.2,
  confidence: 0.8,
  model: "tfidf",
  is_buggy: false,
  bug_type: null,
  explanation: null,
  suggested_fix: null,
  explanation_source: "unavailable",
  verified: false,
};

const run = (overrides: Partial<AnalysisResponse>): AnalysisRun => ({
  code: "def add(a, b):\n    return a + b",
  latencyMs: 10,
  result: { ...base, ...overrides },
});

const renderTab = (h: HealthResponse) =>
  render(
    <ToastProvider>
      <AnalyzeTab health={h} active />
    </ToastProvider>,
  );

function mockFetch(body: unknown) {
  const fn = vi.fn().mockResolvedValue(
    new Response(JSON.stringify(body), { status: 200, headers: { "Content-Type": "application/json" } }),
  );
  vi.stubGlobal("fetch", fn);
  return fn;
}

async function analyzeExample() {
  await userEvent.click(screen.getByRole("button", { name: "Load example" }));
  await userEvent.click(screen.getByRole("button", { name: "Clean helper" }));
  await userEvent.click(screen.getByRole("button", { name: "Analyze" }));
}

afterEach(() => vi.unstubAllGlobals());

describe("summary section", () => {
  it("renders the summary above the verdict with its caption", () => {
    render(
      <ToastProvider>
        <ResultCard
          run={run({ summary: "Add two numbers.", summary_source: "codet5_finetuned" })}
          loading={false}
          error={null}
        />
      </ToastProvider>,
    );
    const section = screen.getByTestId("summary-section");
    expect(within(section).getByText("What this function does")).toBeInTheDocument();
    expect(within(section).getByText("Add two numbers.")).toBeInTheDocument();
    expect(within(section).getByText("Generated by CodeT5")).toBeInTheDocument();
    // Above the bug verdict.
    const verdict = screen.getByTestId("verdict");
    expect(section.compareDocumentPosition(verdict) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy();
  });

  it("says when the summarizer could not run, and is absent when not requested", () => {
    const { rerender } = render(
      <ToastProvider>
        <ResultCard run={run({ summary: null, summary_source: "unavailable" })} loading={false} error={null} />
      </ToastProvider>,
    );
    expect(screen.getByText(/Summary unavailable/)).toBeInTheDocument();
    expect(screen.queryByText("Generated by CodeT5")).not.toBeInTheDocument();

    rerender(
      <ToastProvider>
        <ResultCard run={run({})} loading={false} error={null} />
      </ToastProvider>,
    );
    expect(screen.queryByTestId("summary-section")).not.toBeInTheDocument();
  });
});

describe("summarize toggle", () => {
  it("is disabled with a tooltip when the summary model is unavailable, and nothing is requested", async () => {
    const fetchMock = mockFetch(base);
    renderTab(health("unavailable"));
    const toggle = screen.getByRole("switch", { name: "Summarize function" });
    expect(toggle).toBeDisabled();
    expect(toggle).toHaveAttribute("aria-checked", "false");
    expect(toggle.parentElement).toHaveAttribute("title", expect.stringMatching(/Not trained/));

    await analyzeExample();
    const body = JSON.parse(fetchMock.mock.calls[0][1].body);
    expect(body).not.toHaveProperty("summarize");
  });

  it("is on by default when available, sends summarize=true, and can be switched off", async () => {
    const fetchMock = mockFetch({ ...base, summary: "Split seq into chunks.", summary_source: "codet5_finetuned" });
    renderTab(health("artifacts_present_not_loaded"));
    const toggle = screen.getByRole("switch", { name: "Summarize function" });
    expect(toggle).toBeEnabled();
    expect(toggle).toHaveAttribute("aria-checked", "true");

    await analyzeExample();
    expect(JSON.parse(fetchMock.mock.calls[0][1].body)).toMatchObject({ summarize: true });
    expect(await screen.findByText("Split seq into chunks.")).toBeInTheDocument();

    await userEvent.click(toggle);
    expect(toggle).toHaveAttribute("aria-checked", "false");
    await userEvent.click(screen.getByRole("button", { name: "Analyze" }));
    expect(JSON.parse(fetchMock.mock.calls[1][1].body)).not.toHaveProperty("summarize");
  });

  it("explains how to train the LoRA explainer on its disabled option", () => {
    renderTab(health("loaded"));
    expect(screen.getByRole("radio", { name: "LoRA" })).toBeDisabled();
    expect(screen.getByRole("radio", { name: "LoRA" }).parentElement).toHaveAttribute(
      "title",
      "Needs the CodeT5 LoRA explainer (python -m src.summarization.train_lora)",
    );
  });
});

describe("status pills and client", () => {
  it("shows separate Summary and LoRA explainer pills", () => {
    render(<TopBar tab="analyze" onTab={() => {}} health={health("loaded")} healthError={null} />);
    expect(screen.getByTestId("pill-code_summarizer")).toHaveTextContent("Summary");
    expect(screen.getByTestId("pill-code_summarizer")).toHaveAttribute("data-status", "loaded");
    expect(screen.getByTestId("pill-summarizer")).toHaveTextContent("LoRA explainer");
    expect(screen.getByTestId("pill-summarizer")).toHaveAttribute("data-status", "unavailable");
  });

  it("POSTs only the code to /summarize", async () => {
    const fetchMock = mockFetch({ summary: "Add.", summary_source: "codet5_finetuned", model: "codet5_summarizer" });
    const extra = { code: "x = 1", model: "tfidf" } as unknown as { code: string };
    await api.summarize(extra);
    const [url, init] = fetchMock.mock.calls[0];
    expect(url).toBe("/api/summarize");
    expect(JSON.parse(init.body)).toEqual({ code: "x = 1" });
  });
});
